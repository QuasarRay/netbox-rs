use serde_json::{Map, Value};
use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::error::Error;
use std::fs;
use std::io::{self, Read};
use std::path::{Path, PathBuf};

const GENERATED_MARKER: &str = "// @generated by netbox_openapi_proto; DO NOT EDIT.";
const MANIFEST_FILE: &str = ".netbox-openapi-proto-manifest";
const PROTO_MAX_FIELD_NUMBER: u32 = 536_870_911;

#[derive(Debug)]
struct Config {
    input: String,
    output_dir: PathBuf,
    package: String,
    check: bool,
}

#[derive(Clone, Debug)]
struct FieldType {
    ty: String,
    repeated: bool,
    optional_allowed: bool,
    lossy: bool,
}

#[derive(Clone, Debug)]
struct RequestField {
    source_name: String,
    field_name: String,
    schema: Value,
    required: bool,
    comment: String,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("netbox_openapi_proto: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), Box<dyn Error>> {
    let config = parse_args(env::args().skip(1))?;
    let source = read_input(&config.input)?;
    let document: Value = serde_json::from_str(&source)?;

    validate_openapi(&document)?;

    let files = generate_files(&document, &config.package)?;
    if config.check {
        check_files(&files, &config.output_dir)?;
    } else {
        write_files(&files, &config.output_dir)?;
    }

    Ok(())
}

fn usage() -> &'static str {
    "Usage: netbox_openapi_proto --input <schema.json|-> --output-dir <dir> [--package netbox.v1] [--check]"
}

fn parse_args<I>(args: I) -> Result<Config, Box<dyn Error>>
where
    I: IntoIterator<Item = String>,
{
    let mut input = None;
    let mut output_dir = None;
    let mut package = "netbox.v1".to_string();
    let mut check = false;
    let mut args = args.into_iter();

    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--input" => input = Some(next_arg(&mut args, "--input")?),
            "--output-dir" => {
                output_dir = Some(PathBuf::from(next_arg(&mut args, "--output-dir")?))
            }
            "--package" => package = next_arg(&mut args, "--package")?,
            "--check" => check = true,
            "--help" | "-h" => {
                println!("{}", usage());
                std::process::exit(0);
            }
            unknown => return Err(format!("unknown argument {unknown:?}\n{}", usage()).into()),
        }
    }

    if package.is_empty()
        || !package
            .split('.')
            .all(|part| is_proto_identifier(part) && !part.chars().next().unwrap().is_ascii_digit())
    {
        return Err(format!("invalid protobuf package {package:?}").into());
    }

    Ok(Config {
        input: input.ok_or_else(|| format!("--input is required\n{}", usage()))?,
        output_dir: output_dir.ok_or_else(|| format!("--output-dir is required\n{}", usage()))?,
        package,
        check,
    })
}

fn next_arg<I>(args: &mut I, flag: &str) -> Result<String, Box<dyn Error>>
where
    I: Iterator<Item = String>,
{
    args.next()
        .ok_or_else(|| format!("{flag} requires a value").into())
}

fn read_input(input: &str) -> Result<String, Box<dyn Error>> {
    if input == "-" {
        let mut value = String::new();
        io::stdin().read_to_string(&mut value)?;
        return Ok(value);
    }

    Ok(fs::read_to_string(input)?)
}

fn validate_openapi(document: &Value) -> Result<(), Box<dyn Error>> {
    let version = document
        .get("openapi")
        .and_then(Value::as_str)
        .ok_or("input is missing the OpenAPI version")?;

    if !version.starts_with("3.") {
        return Err(format!("only OpenAPI 3.x is supported, got {version}").into());
    }

    if document.get("paths").and_then(Value::as_object).is_none() {
        return Err("input is missing an OpenAPI paths object".into());
    }

    Ok(())
}

fn generate_files(
    document: &Value,
    package: &str,
) -> Result<BTreeMap<String, String>, Box<dyn Error>> {
    let type_names = build_type_names(document);
    let mut files = BTreeMap::new();

    files.insert(
        "netbox_types.proto".to_string(),
        generate_types_proto(document, package, &type_names)?,
    );

    let services = collect_operations(document);
    for (group, operations) in services {
        let file_name = format!("{}.proto", sanitize_file_name(&group));
        files.insert(
            file_name,
            generate_service_proto(document, package, &group, &operations, &type_names)?,
        );
    }

    Ok(files)
}

fn build_type_names(document: &Value) -> BTreeMap<String, String> {
    let mut result = BTreeMap::new();
    let mut used = BTreeSet::new();

    let Some(schemas) = document
        .pointer("/components/schemas")
        .and_then(Value::as_object)
    else {
        return result;
    };

    for original in schemas.keys() {
        let mut candidate = to_pascal_case(original);
        if candidate.is_empty() {
            candidate = "AnonymousSchema".to_string();
        }
        if candidate
            .chars()
            .next()
            .is_some_and(|ch| ch.is_ascii_digit())
        {
            candidate = format!("Schema{candidate}");
        }

        if used.contains(&candidate) {
            candidate = format!("{candidate}{:08X}", fnv1a(original.as_bytes()));
        }

        used.insert(candidate.clone());
        result.insert(original.clone(), candidate);
    }

    result
}

fn generate_types_proto(
    document: &Value,
    package: &str,
    type_names: &BTreeMap<String, String>,
) -> Result<String, Box<dyn Error>> {
    let mut out = String::new();
    write_header(&mut out, document, package);
    out.push_str("import \"google/protobuf/struct.proto\";\n");
    out.push_str("import \"google/protobuf/timestamp.proto\";\n\n");

    let Some(schemas) = document
        .pointer("/components/schemas")
        .and_then(Value::as_object)
    else {
        return Ok(out);
    };

    for (original, schema) in schemas {
        let name = type_names
            .get(original)
            .expect("all schemas must have a generated type name");
        emit_component_schema(&mut out, document, name, schema, type_names)?;
        out.push('\n');
    }

    Ok(out)
}

fn emit_component_schema(
    out: &mut String,
    document: &Value,
    name: &str,
    schema: &Value,
    type_names: &BTreeMap<String, String>,
) -> Result<(), Box<dyn Error>> {
    if is_enum_schema(schema) {
        emit_enum(out, name, schema);
        return Ok(());
    }

    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        let target = reference_type(reference, type_names)
            .unwrap_or_else(|| "google.protobuf.Value".to_string());
        out.push_str(&format!("message {name} {{\n"));
        let mut used = BTreeSet::new();
        let number = stable_field_number(name, "value", &mut used);
        out.push_str(&format!("  {target} value = {number};\n"));
        out.push_str("}\n");
        return Ok(());
    }

    if schema.get("oneOf").is_some() || schema.get("anyOf").is_some() {
        out.push_str(&format!("message {name} {{\n"));
        out.push_str("  // OpenAPI union retained losslessly as arbitrary JSON.\n");
        let mut used = BTreeSet::new();
        let number = stable_field_number(name, "value", &mut used);
        out.push_str(&format!("  google.protobuf.Value value = {number};\n"));
        out.push_str("}\n");
        return Ok(());
    }

    if schema_type(schema) == Some("array") {
        let null_schema = Value::Null;
        let item_schema = schema.get("items").unwrap_or(&null_schema);
        let field_type = type_for_schema(document, item_schema, type_names, None);
        out.push_str(&format!("message {name} {{\n"));
        let mut used = BTreeSet::new();
        let number = stable_field_number(name, "items", &mut used);
        if field_type.lossy {
            out.push_str("  // Complex OpenAPI item shape represented as JSON.\n");
        }
        out.push_str(&format!("  repeated {} items = {number};\n", field_type.ty));
        out.push_str("}\n");
        return Ok(());
    }

    let (properties, required) = collect_properties(document, schema);
    if !properties.is_empty()
        || schema_type(schema) == Some("object")
        || schema.get("allOf").is_some()
    {
        emit_object_message(
            out,
            document,
            name,
            schema,
            &properties,
            &required,
            type_names,
        );
        return Ok(());
    }

    let field_type = type_for_schema(document, schema, type_names, None);
    out.push_str(&format!("message {name} {{\n"));
    if field_type.lossy {
        out.push_str(
            "  // OpenAPI shape represented as JSON because protobuf has no direct equivalent.\n",
        );
    }
    let mut used = BTreeSet::new();
    let number = stable_field_number(name, "value", &mut used);
    let qualifier = if field_type.repeated { "repeated " } else { "" };
    out.push_str(&format!(
        "  {qualifier}{} value = {number};\n",
        field_type.ty
    ));
    out.push_str("}\n");

    Ok(())
}

fn emit_object_message(
    out: &mut String,
    document: &Value,
    name: &str,
    schema: &Value,
    properties: &BTreeMap<String, Value>,
    required: &BTreeSet<String>,
    type_names: &BTreeMap<String, String>,
) {
    out.push_str(&format!("message {name} {{\n"));

    let inline_enums = inline_enum_types(name, properties);
    for (field_name, (enum_name, enum_schema)) in &inline_enums {
        out.push_str(&format!(
            "  // Inline enum for OpenAPI property {field_name}.\n"
        ));
        emit_nested_enum(out, enum_name, enum_schema, 2);
        out.push('\n');
    }

    let mut used_numbers = BTreeSet::new();

    for (source_name, property) in properties {
        let field_name = proto_field_name(source_name);
        let inline_enum = inline_enums
            .get(source_name)
            .map(|(enum_name, _)| enum_name.as_str());

        let field_type = type_for_schema(document, property, type_names, inline_enum);
        let number = stable_field_number(name, source_name, &mut used_numbers);
        let is_required = required.contains(source_name) && !schema_is_nullable(property);

        if let Some(description) = property.get("description").and_then(Value::as_str) {
            out.push_str(&format!("  // {}\n", one_line(description)));
        }
        if field_type.lossy {
            out.push_str("  // Complex OpenAPI shape represented as JSON.\n");
        }

        let qualifier = if field_type.repeated {
            "repeated "
        } else if !is_required && field_type.optional_allowed {
            "optional "
        } else {
            ""
        };

        out.push_str(&format!(
            "  {qualifier}{} {field_name} = {number};\n",
            field_type.ty
        ));
    }

    if properties.is_empty()
        && let Some(additional) = schema.get("additionalProperties")
    {
        let field_type = if additional == &Value::Bool(true) {
            FieldType {
                ty: "google.protobuf.Value".to_string(),
                repeated: false,
                optional_allowed: false,
                lossy: true,
            }
        } else {
            type_for_schema(document, additional, type_names, None)
        };
        let mut used = BTreeSet::new();
        let number = stable_field_number(name, "entries", &mut used);
        if is_valid_map_value_type(&field_type.ty) && !field_type.repeated {
            out.push_str(&format!(
                "  map<string, {}> entries = {number};\n",
                field_type.ty
            ));
        } else {
            out.push_str(&format!("  google.protobuf.Struct entries = {number};\n"));
        }
    }

    out.push_str("}\n");
}

fn inline_enum_types(
    owner: &str,
    properties: &BTreeMap<String, Value>,
) -> BTreeMap<String, (String, Value)> {
    let mut result = BTreeMap::new();
    let mut used = BTreeSet::new();

    for (field, schema) in properties {
        let candidate_schema = if schema_type(schema) == Some("array") {
            schema.get("items").unwrap_or(schema)
        } else {
            schema
        };

        if candidate_schema.get("$ref").is_some() || !is_enum_schema(candidate_schema) {
            continue;
        }

        let mut name = format!("{}Enum", to_pascal_case(field));
        if name == "Enum" {
            name = format!("{owner}FieldEnum");
        }
        if used.contains(&name) {
            name = format!("{name}{:08X}", fnv1a(field.as_bytes()));
        }
        used.insert(name.clone());
        result.insert(field.clone(), (name, candidate_schema.clone()));
    }

    result
}

fn emit_enum(out: &mut String, name: &str, schema: &Value) {
    out.push_str(&format!("enum {name} {{\n"));
    emit_enum_values(out, name, schema, 2);
    out.push_str("}\n");
}

fn emit_nested_enum(out: &mut String, name: &str, schema: &Value, indent: usize) {
    let prefix = " ".repeat(indent);
    out.push_str(&format!("{prefix}enum {name} {{\n"));
    emit_enum_values(out, name, schema, indent + 2);
    out.push_str(&format!("{prefix}}}\n"));
}

fn emit_enum_values(out: &mut String, name: &str, schema: &Value, indent: usize) {
    let prefix = " ".repeat(indent);
    let enum_prefix = to_upper_snake(name);
    out.push_str(&format!("{prefix}{enum_prefix}_UNSPECIFIED = 0;\n"));

    let mut used = BTreeSet::new();
    used.insert(format!("{enum_prefix}_UNSPECIFIED"));

    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        let mut number = 1u32;
        for value in values {
            if value.is_null() {
                continue;
            }

            let raw = match value {
                Value::String(value) => value.clone(),
                other => other.to_string(),
            };
            let mut variant = format!("{enum_prefix}_{}", to_upper_snake(&raw));
            if variant.ends_with('_') {
                variant.push_str("VALUE");
            }
            if variant == enum_prefix || variant.is_empty() {
                variant = format!("{enum_prefix}_VALUE");
            }
            if variant
                .chars()
                .nth(enum_prefix.len() + 1)
                .is_some_and(|ch| ch.is_ascii_digit())
            {
                variant = format!("{enum_prefix}_VALUE_{}", to_upper_snake(&raw));
            }

            // protoc derives canonical enum/JSON names which can collapse distinct
            // OpenAPI values such as "2.5gbase-t" and "25gbase-t". Preserve the
            // readable spelling while making the exact upstream value part of the
            // generated identifier.
            variant = format!("{variant}_{:08X}", fnv1a(raw.as_bytes()));
            if used.contains(&variant) {
                variant = format!("{variant}_{number}");
            }
            used.insert(variant.clone());
            out.push_str(&format!("{prefix}{variant} = {number};\n"));
            number += 1;
        }
    }
}

fn collect_properties(
    document: &Value,
    schema: &Value,
) -> (BTreeMap<String, Value>, BTreeSet<String>) {
    fn visit(
        document: &Value,
        schema: &Value,
        properties: &mut BTreeMap<String, Value>,
        required: &mut BTreeSet<String>,
        visited_refs: &mut BTreeSet<String>,
    ) {
        if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
            if visited_refs.insert(reference.to_string())
                && let Some(resolved) = resolve_ref(document, reference)
            {
                visit(document, resolved, properties, required, visited_refs);
            }
            return;
        }

        if let Some(all_of) = schema.get("allOf").and_then(Value::as_array) {
            for part in all_of {
                visit(document, part, properties, required, visited_refs);
            }
        }

        if let Some(local_properties) = schema.get("properties").and_then(Value::as_object) {
            for (name, property) in local_properties {
                properties.insert(name.clone(), property.clone());
            }
        }

        if let Some(local_required) = schema.get("required").and_then(Value::as_array) {
            for name in local_required.iter().filter_map(Value::as_str) {
                required.insert(name.to_string());
            }
        }
    }

    let mut properties = BTreeMap::new();
    let mut required = BTreeSet::new();
    let mut visited_refs = BTreeSet::new();
    visit(
        document,
        schema,
        &mut properties,
        &mut required,
        &mut visited_refs,
    );
    (properties, required)
}

fn type_for_schema(
    _document: &Value,
    schema: &Value,
    type_names: &BTreeMap<String, String>,
    inline_enum: Option<&str>,
) -> FieldType {
    if let Some(inline_enum) = inline_enum {
        let repeated = schema_type(schema) == Some("array");
        return FieldType {
            ty: inline_enum.to_string(),
            repeated,
            optional_allowed: !repeated,
            lossy: false,
        };
    }

    if let Some(all_of) = schema.get("allOf").and_then(Value::as_array)
        && all_of.len() == 1
    {
        return type_for_schema(_document, &all_of[0], type_names, inline_enum);
    }

    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        return FieldType {
            ty: reference_type(reference, type_names)
                .unwrap_or_else(|| "google.protobuf.Value".to_string()),
            repeated: false,
            optional_allowed: true,
            lossy: reference_type(reference, type_names).is_none(),
        };
    }

    if schema.get("oneOf").is_some() || schema.get("anyOf").is_some() {
        return FieldType {
            ty: "google.protobuf.Value".to_string(),
            repeated: false,
            optional_allowed: true,
            lossy: true,
        };
    }

    match schema_type(schema) {
        Some("array") => {
            let inner = schema
                .get("items")
                .map(|items| type_for_schema(_document, items, type_names, None))
                .unwrap_or(FieldType {
                    ty: "google.protobuf.Value".to_string(),
                    repeated: false,
                    optional_allowed: true,
                    lossy: true,
                });
            if inner.ty.starts_with("map<") || inner.repeated {
                FieldType {
                    ty: "google.protobuf.Struct".to_string(),
                    repeated: true,
                    optional_allowed: false,
                    lossy: true,
                }
            } else {
                FieldType {
                    ty: inner.ty,
                    repeated: true,
                    optional_allowed: false,
                    lossy: inner.lossy,
                }
            }
        }
        Some("object") => {
            if let Some(additional) = schema.get("additionalProperties") {
                if additional == &Value::Bool(true) {
                    FieldType {
                        ty: "google.protobuf.Struct".to_string(),
                        repeated: false,
                        optional_allowed: true,
                        lossy: false,
                    }
                } else {
                    let value_type = type_for_schema(_document, additional, type_names, None);
                    if is_valid_map_value_type(&value_type.ty) && !value_type.repeated {
                        FieldType {
                            ty: format!("map<string, {}>", value_type.ty),
                            repeated: false,
                            optional_allowed: false,
                            lossy: value_type.lossy,
                        }
                    } else {
                        FieldType {
                            ty: "google.protobuf.Struct".to_string(),
                            repeated: false,
                            optional_allowed: true,
                            lossy: true,
                        }
                    }
                }
            } else {
                FieldType {
                    ty: "google.protobuf.Struct".to_string(),
                    repeated: false,
                    optional_allowed: true,
                    lossy: true,
                }
            }
        }
        Some("integer") => FieldType {
            ty: match schema.get("format").and_then(Value::as_str) {
                Some("int32") => "int32",
                _ => "int64",
            }
            .to_string(),
            repeated: false,
            optional_allowed: true,
            lossy: false,
        },
        Some("number") => FieldType {
            ty: match schema.get("format").and_then(Value::as_str) {
                Some("float") => "float",
                _ => "double",
            }
            .to_string(),
            repeated: false,
            optional_allowed: true,
            lossy: false,
        },
        Some("boolean") => FieldType {
            ty: "bool".to_string(),
            repeated: false,
            optional_allowed: true,
            lossy: false,
        },
        Some("string") => FieldType {
            ty: match schema.get("format").and_then(Value::as_str) {
                Some("date-time") => "google.protobuf.Timestamp",
                Some("binary") | Some("byte") => "bytes",
                _ => "string",
            }
            .to_string(),
            repeated: false,
            optional_allowed: true,
            lossy: false,
        },
        _ => FieldType {
            ty: "google.protobuf.Value".to_string(),
            repeated: false,
            optional_allowed: true,
            lossy: true,
        },
    }
}

fn is_valid_map_value_type(ty: &str) -> bool {
    !ty.starts_with("map<")
}

fn schema_is_nullable(schema: &Value) -> bool {
    if schema.get("nullable").and_then(Value::as_bool) == Some(true) {
        return true;
    }

    schema
        .get("type")
        .and_then(Value::as_array)
        .is_some_and(|types| types.iter().any(|value| value.as_str() == Some("null")))
}

fn schema_type(schema: &Value) -> Option<&str> {
    match schema.get("type") {
        Some(Value::String(value)) => Some(value),
        Some(Value::Array(values)) => values
            .iter()
            .filter_map(Value::as_str)
            .find(|value| *value != "null"),
        _ => {
            if schema.get("properties").is_some() || schema.get("additionalProperties").is_some() {
                Some("object")
            } else {
                None
            }
        }
    }
}

fn is_enum_schema(schema: &Value) -> bool {
    schema.get("enum").and_then(Value::as_array).is_some()
}

fn reference_type(reference: &str, type_names: &BTreeMap<String, String>) -> Option<String> {
    let name = reference.rsplit('/').next()?;
    let decoded = name.replace("~1", "/").replace("~0", "~");
    type_names.get(&decoded).cloned()
}

fn collect_operations(document: &Value) -> BTreeMap<String, Vec<(String, String, Value)>> {
    let mut services: BTreeMap<String, Vec<(String, String, Value)>> = BTreeMap::new();
    let Some(paths) = document.get("paths").and_then(Value::as_object) else {
        return services;
    };

    for (path, path_item) in paths {
        let Some(path_item) = path_item.as_object() else {
            continue;
        };

        for method in ["get", "post", "put", "patch", "delete"] {
            if let Some(operation) = path_item.get(method)
                && operation.is_object()
            {
                services.entry(service_group(path)).or_default().push((
                    method.to_string(),
                    path.clone(),
                    operation.clone(),
                ));
            }
        }
    }

    for operations in services.values_mut() {
        operations.sort_by(|a, b| {
            a.1.cmp(&b.1)
                .then_with(|| a.0.cmp(&b.0))
                .then_with(|| operation_id(&a.0, &a.1, &a.2).cmp(&operation_id(&b.0, &b.1, &b.2)))
        });
    }

    services
}

fn service_group(path: &str) -> String {
    let parts: Vec<_> = path.split('/').filter(|part| !part.is_empty()).collect();
    if parts.first() == Some(&"api") {
        parts.get(1).copied().unwrap_or("api").to_string()
    } else {
        parts.first().copied().unwrap_or("root").to_string()
    }
}

fn generate_service_proto(
    document: &Value,
    package: &str,
    group: &str,
    operations: &[(String, String, Value)],
    type_names: &BTreeMap<String, String>,
) -> Result<String, Box<dyn Error>> {
    let mut out = String::new();
    write_header(&mut out, document, package);
    out.push_str("import \"google/protobuf/empty.proto\";\n");
    out.push_str("import \"google/protobuf/struct.proto\";\n");
    out.push_str("import \"google/protobuf/timestamp.proto\";\n");
    out.push_str("import \"netbox_types.proto\";\n\n");

    let service_name = format!("{}Service", to_pascal_case(group));
    let mut messages = String::new();
    let mut rpc_lines = String::new();
    let mut used_rpc_names = BTreeSet::new();

    for (method, path, operation) in operations {
        let raw_operation_id = operation_id(method, path, operation);
        let mut rpc_name = to_pascal_case(&raw_operation_id);
        if rpc_name.is_empty() {
            rpc_name = format!(
                "{}{}",
                to_pascal_case(method),
                to_pascal_case(&path.replace('/', "_"))
            );
        }
        if rpc_name
            .chars()
            .next()
            .is_some_and(|ch| ch.is_ascii_digit())
        {
            rpc_name = format!("Operation{rpc_name}");
        }
        if used_rpc_names.contains(&rpc_name) {
            rpc_name = format!("{rpc_name}{:08X}", fnv1a(raw_operation_id.as_bytes()));
        }
        used_rpc_names.insert(rpc_name.clone());

        let request_type = emit_request_message(
            &mut messages,
            document,
            path,
            operation,
            &rpc_name,
            type_names,
        )?;
        let response_type =
            emit_response_message(&mut messages, document, operation, &rpc_name, type_names);

        let summary = operation
            .get("summary")
            .and_then(Value::as_str)
            .or_else(|| operation.get("description").and_then(Value::as_str))
            .unwrap_or("");
        rpc_lines.push_str(&format!(
            "  // {} {}{}{}\n",
            method.to_ascii_uppercase(),
            path,
            if summary.is_empty() { "" } else { " - " },
            one_line(summary),
        ));
        rpc_lines.push_str(&format!(
            "  rpc {rpc_name} ({request_type}) returns ({response_type});\n"
        ));
    }

    out.push_str(&messages);
    if !messages.is_empty() {
        out.push('\n');
    }
    out.push_str(&format!("service {service_name} {{\n"));
    out.push_str(&rpc_lines);
    out.push_str("}\n");

    Ok(out)
}

fn emit_request_message(
    out: &mut String,
    document: &Value,
    path: &str,
    operation: &Value,
    rpc_name: &str,
    type_names: &BTreeMap<String, String>,
) -> Result<String, Box<dyn Error>> {
    let mut fields = Vec::new();

    let path_item = document
        .get("paths")
        .and_then(Value::as_object)
        .and_then(|paths| paths.get(path));

    for parameter in path_item
        .and_then(|item| item.get("parameters"))
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .chain(
            operation
                .get("parameters")
                .and_then(Value::as_array)
                .into_iter()
                .flatten(),
        )
    {
        if let Some(parameter) = resolve_object(document, parameter)
            && let (Some(name), Some(location), Some(schema)) = (
                parameter.get("name").and_then(Value::as_str),
                parameter.get("in").and_then(Value::as_str),
                parameter.get("schema"),
            )
        {
            fields.push(RequestField {
                source_name: name.to_string(),
                field_name: proto_field_name(name),
                schema: schema.clone(),
                required: parameter
                    .get("required")
                    .and_then(Value::as_bool)
                    .unwrap_or(false),
                comment: format!("{location} parameter"),
            });
        }
    }

    if let Some(request_body) = operation
        .get("requestBody")
        .and_then(|body| resolve_object(document, body))
        && let Some(schema) = content_schema(request_body)
    {
        fields.push(RequestField {
            source_name: "body".to_string(),
            field_name: "body".to_string(),
            schema: schema.clone(),
            required: request_body
                .get("required")
                .and_then(Value::as_bool)
                .unwrap_or(false),
            comment: "request body".to_string(),
        });
    }

    if fields.is_empty() {
        return Ok("google.protobuf.Empty".to_string());
    }

    let message_name = format!("{rpc_name}Request");
    deduplicate_request_field_names(&mut fields);

    out.push_str(&format!("message {message_name} {{\n"));
    let mut used_numbers = BTreeSet::new();
    for field in fields {
        let field_type = type_for_schema(document, &field.schema, type_names, None);
        let number = stable_field_number(
            &message_name,
            &format!("{}:{}", field.comment, field.source_name),
            &mut used_numbers,
        );
        out.push_str(&format!("  // {}: {}\n", field.comment, field.source_name));
        if field_type.lossy {
            out.push_str("  // Complex OpenAPI shape represented as JSON.\n");
        }
        let effective_required = field.required && !schema_is_nullable(&field.schema);
        let qualifier = if field_type.repeated {
            "repeated "
        } else if !effective_required && field_type.optional_allowed {
            "optional "
        } else {
            ""
        };
        out.push_str(&format!(
            "  {qualifier}{} {} = {number};\n",
            field_type.ty, field.field_name
        ));
    }
    out.push_str("}\n\n");

    Ok(message_name)
}

fn deduplicate_request_field_names(fields: &mut [RequestField]) {
    let mut counts = BTreeMap::<String, usize>::new();
    for field in fields.iter() {
        *counts.entry(field.field_name.clone()).or_default() += 1;
    }

    for field in fields.iter_mut() {
        if counts.get(&field.field_name).copied().unwrap_or(0) > 1 {
            let prefix = field.comment.split_whitespace().next().unwrap_or("value");
            field.field_name = proto_field_name(&format!("{prefix}_{}", field.source_name));
        }
    }
}

fn emit_response_message(
    out: &mut String,
    document: &Value,
    operation: &Value,
    rpc_name: &str,
    type_names: &BTreeMap<String, String>,
) -> String {
    let Some(responses) = operation.get("responses").and_then(Value::as_object) else {
        return "google.protobuf.Empty".to_string();
    };

    let mut success_codes: Vec<_> = responses
        .keys()
        .filter(|code| code.starts_with('2'))
        .cloned()
        .collect();
    success_codes.sort();

    let Some(code) = success_codes.first() else {
        return "google.protobuf.Empty".to_string();
    };
    let Some(response) = responses
        .get(code)
        .and_then(|response| resolve_object(document, response))
    else {
        return "google.protobuf.Empty".to_string();
    };

    let Some(schema) = content_schema(response) else {
        return "google.protobuf.Empty".to_string();
    };

    if let Some(reference) = schema.get("$ref").and_then(Value::as_str)
        && let Some(ty) = reference_type(reference, type_names)
    {
        return ty;
    }

    let message_name = format!("{rpc_name}Response");
    let field_type = type_for_schema(document, schema, type_names, None);

    out.push_str(&format!("message {message_name} {{\n"));
    if field_type.lossy {
        out.push_str("  // Complex OpenAPI response represented as JSON.\n");
    }
    let mut used = BTreeSet::new();
    let number = stable_field_number(&message_name, "result", &mut used);
    let qualifier = if field_type.repeated { "repeated " } else { "" };
    out.push_str(&format!(
        "  {qualifier}{} result = {number};\n",
        field_type.ty
    ));
    out.push_str("}\n\n");

    message_name
}

fn operation_id(method: &str, path: &str, operation: &Value) -> String {
    operation
        .get("operationId")
        .and_then(Value::as_str)
        .map(ToOwned::to_owned)
        .unwrap_or_else(|| {
            format!(
                "{}_{}",
                method,
                path.trim_matches('/')
                    .replace(&['/', '{', '}', '-'][..], "_")
            )
        })
}

fn resolve_object<'a>(document: &'a Value, value: &'a Value) -> Option<&'a Map<String, Value>> {
    if let Some(reference) = value.get("$ref").and_then(Value::as_str) {
        resolve_ref(document, reference)?.as_object()
    } else {
        value.as_object()
    }
}

fn resolve_ref<'a>(document: &'a Value, reference: &str) -> Option<&'a Value> {
    let pointer = reference.strip_prefix('#')?;
    document.pointer(pointer)
}

fn content_schema(object: &Map<String, Value>) -> Option<&Value> {
    let content = object.get("content")?.as_object()?;

    if let Some(schema) = content
        .get("application/json")
        .and_then(Value::as_object)
        .and_then(|media| media.get("schema"))
    {
        return Some(schema);
    }

    if let Some(schema) = content
        .iter()
        .find(|(content_type, _)| content_type.ends_with("+json"))
        .and_then(|(_, media)| media.as_object())
        .and_then(|media| media.get("schema"))
    {
        return Some(schema);
    }

    content
        .values()
        .find_map(Value::as_object)
        .and_then(|media| media.get("schema"))
}

fn write_header(out: &mut String, document: &Value, package: &str) {
    let version = document
        .pointer("/info/version")
        .and_then(Value::as_str)
        .unwrap_or("unknown");
    out.push_str(GENERATED_MARKER);
    out.push('\n');
    out.push_str(&format!("// NetBox OpenAPI version: {version}\n"));
    out.push_str("// Source contract: NetBox contrib/openapi.json\n\n");
    out.push_str("syntax = \"proto3\";\n\n");
    out.push_str(&format!("package {package};\n\n"));
}

fn write_files(files: &BTreeMap<String, String>, output_dir: &Path) -> Result<(), Box<dyn Error>> {
    fs::create_dir_all(output_dir)?;
    let manifest_path = output_dir.join(MANIFEST_FILE);

    if let Ok(old_manifest) = fs::read_to_string(&manifest_path) {
        let new_names: BTreeSet<_> = files.keys().cloned().collect();
        for old_name in old_manifest.lines().filter(|line| !line.trim().is_empty()) {
            if !new_names.contains(old_name) {
                let stale = output_dir.join(old_name);
                if stale.is_file() {
                    fs::remove_file(stale)?;
                }
            }
        }
    }

    for (name, content) in files {
        let path = output_dir.join(name);
        if fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
            fs::write(path, content)?;
        }
    }

    let manifest = files.keys().cloned().collect::<Vec<_>>().join("\n") + "\n";
    fs::write(manifest_path, manifest)?;
    Ok(())
}

fn check_files(files: &BTreeMap<String, String>, output_dir: &Path) -> Result<(), Box<dyn Error>> {
    let mut mismatches = Vec::new();

    for (name, expected) in files {
        let path = output_dir.join(name);
        match fs::read_to_string(&path) {
            Ok(actual) if actual == *expected => {}
            Ok(_) => mismatches.push(format!("changed: {}", path.display())),
            Err(_) => mismatches.push(format!("missing: {}", path.display())),
        }
    }

    let manifest_path = output_dir.join(MANIFEST_FILE);
    let expected_manifest = files.keys().cloned().collect::<Vec<_>>().join("\n") + "\n";
    match fs::read_to_string(&manifest_path) {
        Ok(actual) if actual == expected_manifest => {}
        Ok(_) => mismatches.push(format!("changed: {}", manifest_path.display())),
        Err(_) => mismatches.push(format!("missing: {}", manifest_path.display())),
    }

    if mismatches.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "generated protobufs are stale:\n{}",
            mismatches
                .into_iter()
                .map(|value| format!("  {value}"))
                .collect::<Vec<_>>()
                .join("\n")
        )
        .into())
    }
}

fn stable_field_number(owner: &str, field: &str, used: &mut BTreeSet<u32>) -> u32 {
    let key = format!("{owner}.{field}");
    let mut number = (fnv1a(key.as_bytes()) % (PROTO_MAX_FIELD_NUMBER - 1)) + 1;

    loop {
        if (19_000..=19_999).contains(&number) {
            number = 20_000;
        }
        if used.insert(number) {
            return number;
        }
        number += 1;
        if number > PROTO_MAX_FIELD_NUMBER {
            number = 1;
        }
    }
}

fn fnv1a(bytes: &[u8]) -> u32 {
    let mut hash = 0x811c9dc5u32;
    for byte in bytes {
        hash ^= u32::from(*byte);
        hash = hash.wrapping_mul(0x01000193);
    }
    hash
}

fn sanitize_file_name(value: &str) -> String {
    let mut result = to_snake_case(value);
    if result.is_empty() {
        result = "api".to_string();
    }
    result
}

fn proto_field_name(value: &str) -> String {
    let mut result = to_snake_case(value);
    if result.is_empty() {
        result = "value".to_string();
    }
    if result.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        result = format!("field_{result}");
    }
    if is_proto_keyword(&result) {
        result.push_str("_field");
    }
    result
}

fn to_pascal_case(value: &str) -> String {
    split_words(value)
        .into_iter()
        .map(|word| {
            let mut chars = word.chars();
            let Some(first) = chars.next() else {
                return String::new();
            };
            let mut result = first.to_ascii_uppercase().to_string();
            result.push_str(&chars.as_str().to_ascii_lowercase());
            result
        })
        .collect()
}

fn to_snake_case(value: &str) -> String {
    split_words(value)
        .into_iter()
        .map(|word| word.to_ascii_lowercase())
        .collect::<Vec<_>>()
        .join("_")
}

fn to_upper_snake(value: &str) -> String {
    let value = split_words(value)
        .into_iter()
        .map(|word| word.to_ascii_uppercase())
        .collect::<Vec<_>>()
        .join("_");
    if value.is_empty() {
        "VALUE".to_string()
    } else {
        value
    }
}

fn split_words(value: &str) -> Vec<String> {
    let chars: Vec<char> = value.chars().collect();
    let mut words = Vec::new();
    let mut current = String::new();

    for (index, ch) in chars.iter().copied().enumerate() {
        if !ch.is_ascii_alphanumeric() {
            if !current.is_empty() {
                words.push(std::mem::take(&mut current));
            }
            continue;
        }

        let previous = index.checked_sub(1).and_then(|i| chars.get(i)).copied();
        let next = chars.get(index + 1).copied();

        let boundary = !current.is_empty()
            && ch.is_ascii_uppercase()
            && (previous.is_some_and(|p| p.is_ascii_lowercase() || p.is_ascii_digit())
                || (previous.is_some_and(|p| p.is_ascii_uppercase())
                    && next.is_some_and(|n| n.is_ascii_lowercase())));

        if boundary {
            words.push(std::mem::take(&mut current));
        }
        current.push(ch);
    }

    if !current.is_empty() {
        words.push(current);
    }

    words
}

fn is_proto_identifier(value: &str) -> bool {
    !value.is_empty()
        && value
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || ch == '_')
}

fn is_proto_keyword(value: &str) -> bool {
    matches!(
        value,
        "syntax"
            | "import"
            | "weak"
            | "public"
            | "package"
            | "option"
            | "optional"
            | "required"
            | "repeated"
            | "oneof"
            | "map"
            | "extensions"
            | "to"
            | "max"
            | "reserved"
            | "enum"
            | "message"
            | "service"
            | "rpc"
            | "returns"
            | "stream"
            | "double"
            | "float"
            | "int32"
            | "int64"
            | "uint32"
            | "uint64"
            | "sint32"
            | "sint64"
            | "fixed32"
            | "fixed64"
            | "sfixed32"
            | "sfixed64"
            | "bool"
            | "string"
            | "bytes"
    )
}

fn one_line(value: &str) -> String {
    value.split_whitespace().collect::<Vec<_>>().join(" ")
}

